const fs = require("fs");
const path = require("path");
const os = require("os");
const zlib = require("zlib");

const DEFAULT_SOURCE = "C:\\Users\\Administrator\\Desktop\\2025艺术综合分历史组与物理组综合分排名表.xlsx";
const DEFAULT_TARGET = path.resolve(__dirname, "..", "shared", "fujian-art-rank-2025.js");

function inflateRaw(buffer) {
  return zlib.inflateRawSync(buffer);
}

function readUInt16(buffer, offset) {
  return buffer.readUInt16LE(offset);
}

function readUInt32(buffer, offset) {
  return buffer.readUInt32LE(offset);
}

function unzipEntries(filePath) {
  const buffer = fs.readFileSync(filePath);
  const entries = new Map();
  let offset = 0;
  while (offset < buffer.length - 4) {
    const signature = readUInt32(buffer, offset);
    if (signature !== 0x04034b50) {
      offset += 1;
      continue;
    }
    const method = readUInt16(buffer, offset + 8);
    const compressedSize = readUInt32(buffer, offset + 18);
    const fileNameLength = readUInt16(buffer, offset + 26);
    const extraLength = readUInt16(buffer, offset + 28);
    const nameStart = offset + 30;
    const dataStart = nameStart + fileNameLength + extraLength;
    const name = buffer.slice(nameStart, nameStart + fileNameLength).toString("utf8");
    const compressed = buffer.slice(dataStart, dataStart + compressedSize);
    let content;
    if (method === 0) content = compressed;
    else if (method === 8) content = inflateRaw(compressed);
    else throw new Error(`Unsupported zip compression method ${method} for ${name}`);
    entries.set(name.replace(/\\/g, "/"), content);
    offset = dataStart + compressedSize;
  }
  return entries;
}

function decodeXml(text) {
  return String(text)
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, "\"")
    .replace(/&apos;/g, "'");
}

function columnOf(ref) {
  return (String(ref).match(/[A-Z]+/) || [""])[0];
}

function loadSharedStrings(entries) {
  const xml = entries.get("xl/sharedStrings.xml");
  if (!xml) return [];
  return [...xml.toString("utf8").matchAll(/<si>([\s\S]*?)<\/si>/g)].map((match) => {
    const text = [...match[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((part) => part[1]).join("");
    return decodeXml(text);
  });
}

function parseSheetRows(entries) {
  const sheet = entries.get("xl/worksheets/sheet1.xml");
  if (!sheet) throw new Error("Cannot find xl/worksheets/sheet1.xml");
  const sharedStrings = loadSharedStrings(entries);
  const xml = sheet.toString("utf8");
  return [...xml.matchAll(/<row[^>]*r="(\d+)"[^>]*>([\s\S]*?)<\/row>/g)].map((rowMatch) => {
    const cells = {};
    for (const cellMatch of rowMatch[2].matchAll(/<c[^>]*r="([A-Z]+\d+)"([^>]*)>([\s\S]*?)<\/c>/g)) {
      const ref = cellMatch[1];
      const attrs = cellMatch[2];
      const body = cellMatch[3];
      const raw = body.match(/<v>([\s\S]*?)<\/v>/)?.[1] ?? body.match(/<t[^>]*>([\s\S]*?)<\/t>/)?.[1] ?? "";
      let value = raw;
      if (/t="s"/.test(attrs)) value = sharedStrings[Number(raw)] ?? raw;
      else if (/t="inlineStr"/.test(attrs)) value = decodeXml(raw);
      else if (raw !== "" && Number.isFinite(Number(raw))) value = Number(raw);
      cells[columnOf(ref)] = value;
    }
    return cells;
  });
}

function pairRows(rows, scoreColumn, rankColumn) {
  return rows
    .map((row) => ({
      score: Number(row[scoreColumn]),
      rank: Number(row[rankColumn]),
      count: "",
    }))
    .filter((row) => Number.isFinite(row.score) && Number.isFinite(row.rank));
}

function importRankData(sourcePath) {
  const entries = unzipEntries(sourcePath);
  const rows = parseSheetRows(entries).slice(2);
  return {
    history: pairRows(rows, "A", "B"),
    physics: pairRows(rows, "D", "E"),
  };
}

function buildModule(rankData, sourceLabel) {
  return `// 2025 Fujian art comprehensive score ranking table.
// Generated by scripts/import-2025-rank-xlsx.js from ${sourceLabel}.
const rankData2025BySubject = ${JSON.stringify(rankData, null, 2)};

if (typeof module !== "undefined" && module.exports) {
  module.exports = { rankData2025BySubject };
}

if (typeof window !== "undefined") {
  window.FujianArtRank2025 = { rankData2025BySubject };
}
`;
}

function main() {
  const args = process.argv.slice(2);
  const sourcePath = args.find((arg) => !arg.startsWith("--")) || DEFAULT_SOURCE;
  const targetFlagIndex = args.indexOf("--out");
  const targetPath = targetFlagIndex >= 0 ? path.resolve(args[targetFlagIndex + 1]) : DEFAULT_TARGET;
  const jsonOnly = args.includes("--json");

  if (!fs.existsSync(sourcePath)) throw new Error(`Source xlsx not found: ${sourcePath}`);
  const rankData = importRankData(sourcePath);

  if (jsonOnly) {
    process.stdout.write(JSON.stringify(rankData, null, 2));
    return;
  }

  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  const label = path.basename(sourcePath);
  fs.writeFileSync(targetPath, buildModule(rankData, label), "utf8");
  console.log(JSON.stringify({
    source: sourcePath,
    target: targetPath,
    historyRows: rankData.history.length,
    physicsRows: rankData.physics.length,
  }, null, 2));
}

if (require.main === module) {
  main();
}

module.exports = { importRankData, buildModule };
